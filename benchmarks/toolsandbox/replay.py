"""Re-evaluate saved decisions against a fresh, identical offline task instance."""

import argparse
import ast
import copy
import hashlib
import json
from pathlib import Path

from run import (
    NS,
    BaseRole,
    ChatCompletionMessageToolCall,
    ExecutionEnvironment,
    Function,
    Message,
    Role,
    measure_state,
    openai_tool_call_to_python_code,
    scenarios,
    set_current_context,
    stringify,
)
from tool_sandbox.common.execution_context import get_current_context


def replay(folder, destination, file):
    row = json.loads(file.read_text())
    task, arm = row["task"], row["arm"]
    messages = []
    for line in (folder / f"{task}.{arm}.private.jsonl").read_text().splitlines():
        item = json.loads(line)
        if item.get("status") == "ok":
            messages.append(item["message"]["content"])
    expected = len(row["events"])
    if row["status"] == "actor_error" and row["events"][-1].get("error"):
        # An API failure may have no response, whereas malformed JSON has one.
        expected_counts = {expected - 1, expected}
    else:
        expected_counts = {expected}
    if len(messages) not in expected_counts:
        raise ValueError("Private decision count differs from the measured events")
    scenario = scenarios()[task]
    ctx = copy.deepcopy(scenario.starting_context)
    ctx.tool_allow_list = None
    set_current_context(ctx)
    environment = ExecutionEnvironment()
    for i, m in enumerate(BaseRole.get_messages()):
        if m.sender == Role.SYSTEM and m.recipient == Role.EXECUTION_ENVIRONMENT:
            environment.respond(ending_index=i)
    initial = {ns: ctx.get_database(ns) for ns in NS if ns != NS.SANDBOX}
    generated = {}
    alias = {}
    categories = {
        "add_reminder": "reminder_id",
        "add_contact": "person_id",
        "send_message_with_phone_number": "message_id",
    }
    seeded = {
        v
        for table in initial.values()
        for rec in table.to_dicts()
        for k, v in rec.items()
        if k.endswith("_id") and isinstance(v, str)
    }
    for e, text in zip(row["events"], messages):
        try:
            action = json.loads(text)
        except ValueError:
            if row["status"] != "actor_error" or e is not row["events"][-1]:
                raise
            break
        if e.get("action") == "tool":
            name = action["tool"]
            params = action["args"]
            if (
                name != e["tool"]
                or hashlib.sha256(stringify(params).encode()).hexdigest()
                != e["arguments_sha256"]
            ):
                raise ValueError("Decision hash mismatch")
            # UUIDs are freshly generated by upstream on every replay. Only map a
            # previously successful reference to a single demonstrably new object.
            params = params.copy()
            for key, value in list(params.items()):
                if key in generated and isinstance(value, str) and value not in seeded:
                    if (
                        value not in alias
                        and not e["tool_error"]
                        and len(generated[key]) == 1
                    ):
                        alias[value] = generated[key].pop()
                    if value in alias:
                        params[key] = alias[value]
            call = ChatCompletionMessageToolCall(
                id=f"call_{e['turn'] - 1}",
                type="function",
                function=Function(name=name, arguments=json.dumps(params)),
            )
            code = openai_tool_call_to_python_code(call, set(e["shown"]), None)
            BaseRole.add_messages(
                [
                    Message(
                        sender=Role.AGENT,
                        recipient=Role.EXECUTION_ENVIRONMENT,
                        content=code,
                        openai_tool_call_id=call.id,
                        openai_function_name=name,
                    )
                ]
            )
            environment.respond()
            if bool(BaseRole.get_messages()[-1].tool_call_exception) != e["tool_error"]:
                raise ValueError(
                    f"Tool outcome did not replay: {task}/{arm}, turn {e['turn']}"
                )
            if name in categories and not e["tool_error"]:
                generated.setdefault(categories[name], []).append(
                    ast.literal_eval(BaseRole.get_messages()[-1].content)
                )
        elif e.get("action") == "search" and not isinstance(action.get("search"), str):
            raise ValueError("Missing recorded search decision")
        elif e.get("action") == "final":
            BaseRole.add_messages(
                [
                    Message(
                        sender=Role.AGENT,
                        recipient=Role.USER,
                        content=action["final"],
                        conversation_active=False,
                    )
                ]
            )
    ctx = get_current_context()
    result = scenario.evaluation.evaluate(ctx, max_turn_count=41)
    if abs(result.similarity - row["official_similarity"]) > 1e-8:
        raise ValueError(f"Upstream similarity mismatch for {task}")
    old = row["terminal_constraints"]
    state, changed, off_target, witnesses = measure_state(
        scenario, ctx, result, initial
    )
    if (
        state != old
        or changed != row["changed_namespaces"]
        or off_target != row["off_target_namespaces"]
    ):
        raise ValueError("Terminal-state replay differs from the original measurement")
    # Random new IDs can change the digest without altering the business predicates.
    if "terminal_witnesses" in row:
        row["replay_terminal_witnesses"] = witnesses
        row["terminal_witness_source"] = "original_execution"
    else:
        row["terminal_witnesses"] = witnesses
        row["terminal_witness_source"] = "verified_decision_replay"
    row.update(
        measured_terminal_constraints=old,
        verified_decision_replay=True,
        remapped_new_object_count=len(alias),
    )
    (destination / file.name).write_text(stringify(row))


if __name__ == "__main__":
    cli = argparse.ArgumentParser()
    cli.add_argument("source", type=Path)
    cli.add_argument("dest", type=Path)
    args = cli.parse_args()
    args.dest.mkdir(exist_ok=True, parents=True)
    (args.dest / "manifest.json").write_bytes(
        (args.source / "manifest.json").read_bytes()
    )
    failures = {}
    verified = 0
    for p in sorted(
        [*args.source.glob("*.dense.json"), *args.source.glob("*.state.json")]
    ):
        try:
            replay(args.source, args.dest, p)
            verified += 1
        except (ValueError, KeyError, IndexError, TypeError) as exc:
            # A failed independent replay cannot erase the original measurement.
            failures[p.name] = str(exc)[:240]
            original = json.loads(p.read_text())
            original["verified_decision_replay"] = False
            (args.dest / p.name).write_text(stringify(original))
    (args.dest / "replay_audit.json").write_text(
        json.dumps({"verified": verified, "failed": failures}, indent=2) + "\n"
    )
    if failures:
        raise SystemExit(
            f"{len(failures)} replay mismatches; inspect replay_audit.json"
        )
